#!/usr/bin/env node
// Single source of truth for the release version: the root VERSION file.
//
//   node scripts/release/set-version.mjs <version>        write VERSION, all package.json files,
//                                                         packages/shared/src/version.ts and
//                                                         apps/android/gradle.properties
//   node scripts/release/set-version.mjs --check [tag]    verify everything matches VERSION (and
//                                                         the git tag "v<VERSION>" when given)
//   node scripts/release/set-version.mjs --print          print "<version> <versionCode>"
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseVersion, versionCode } from './version.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const abs = (p) => join(root, p);
const read = (p) => (existsSync(abs(p)) ? readFileSync(abs(p), 'utf8') : '');

function packageJsonFiles() {
  const files = ['package.json'];
  for (const dir of ['apps', 'packages']) {
    for (const entry of readdirSync(abs(dir), { withFileTypes: true })) {
      const p = `${dir}/${entry.name}/package.json`;
      if (entry.isDirectory() && existsSync(abs(p))) files.push(p);
    }
  }
  return files;
}

function targets(version) {
  const code = versionCode(version);
  const out = [];
  for (const path of packageJsonFiles()) {
    const text = read(path);
    out.push({
      path,
      text,
      current: /"version":\s*"([^"]*)"/.exec(text)?.[1],
      expected: version,
      next: text.replace(/("version":\s*")[^"]*(")/, `$1${version}$2`),
    });
  }
  const gradle = read('apps/android/gradle.properties');
  out.push({
    path: 'apps/android/gradle.properties',
    text: gradle,
    current: `${/^tix\.versionName=(.*)$/m.exec(gradle)?.[1]}/${/^tix\.versionCode=(.*)$/m.exec(gradle)?.[1]}`,
    expected: `${version}/${code}`,
    next: gradle
      .replace(/^tix\.versionName=.*$/m, `tix.versionName=${version}`)
      .replace(/^tix\.versionCode=.*$/m, `tix.versionCode=${code}`),
  });
  const ts = read('packages/shared/src/version.ts');
  out.push({
    path: 'packages/shared/src/version.ts',
    text: ts,
    current: /'([^']*)'/.exec(ts)?.[1],
    expected: version,
    next:
      '// Generated by scripts/release/set-version.mjs from the root VERSION file - do not edit.\n' +
      `export const APP_VERSION = '${version}';\n`,
  });
  const file = read('VERSION');
  out.push({
    path: 'VERSION',
    text: file,
    current: file.trim(),
    expected: version,
    next: `${version}\n`,
  });
  return out;
}

const [arg, extra] = process.argv.slice(2);
try {
  if (arg === '--print') {
    const v = read('VERSION').trim();
    console.log(`${v} ${versionCode(v)}`);
  } else if (arg === '--check') {
    const version = read('VERSION').trim();
    parseVersion(version);
    const bad = targets(version).filter((t) => t.current !== t.expected);
    if (extra && extra.replace(/^refs\/tags\//, '') !== `v${version}`) {
      bad.push({ path: `git tag ${extra}`, current: extra, expected: `v${version}` });
    }
    for (const b of bad) console.error(`${b.path}: found "${b.current}", expected "${b.expected}"`);
    if (bad.length) process.exit(1);
    console.log(`Version ${version} (versionCode ${versionCode(version)}) is consistent.`);
  } else if (arg && !arg.startsWith('-')) {
    const version = arg.replace(/^v/, '');
    parseVersion(version);
    for (const t of targets(version)) {
      if (t.next !== t.text) writeFileSync(abs(t.path), t.next);
    }
    console.log(`Version set to ${version} (Android versionCode ${versionCode(version)}).`);
  } else {
    console.error('usage: set-version.mjs <version> | --check [tag] | --print');
    process.exit(2);
  }
} catch (err) {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
}
