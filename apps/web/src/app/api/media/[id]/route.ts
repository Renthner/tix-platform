import {
  findMediaVariant,
  getMediaAsset,
  loadMediaBytes,
  loadMediaVariantBytes,
  type MediaVariantRow,
} from '@tix/core';
import {
  MEDIA_VARIANT_MIME,
  isPublicMediaKind,
  parseMediaVariantQuery,
  publicMediaCacheControl,
} from '@tix/shared';
import { adminForApi } from '@/server/auth';
import { getCore } from '@/server/core';
import { apiError, handle, uuidParam } from '@/server/http';

export const dynamic = 'force-dynamic';

/**
 * GET – media delivery.
 * Public kinds (event / venue images, logos, e-mail images; see `PUBLIC_MEDIA_KINDS`) are served
 * to everyone. The original under its id URL revalidates (ETag = hash of the stored master, which
 * a one-off clean-up of legacy files may replace); variants are cached immutably.
 * Private kinds (ticket backgrounds, wallet images, documents, other) require an admin session
 * and are never cached by shared caches. `?download=1` forces a download instead of inline display.
 * `?w=<width>&f=avif|webp` returns the smallest AVIF / WebP variant that is at least that wide
 * (the widest one if the source is narrower); `w` and `f` are allow-listed. Assets without a
 * variant in that format (private kinds, not yet converted) answer with the original, cached
 * only briefly so the variant is picked up once the worker has generated it; a variant is cached
 * for a year only once generation has finished and it is the requested or the widest width.
 * Variants are generated by the worker after the upload, not in the request.
 */
export async function GET(request: Request, { params }: { params: Promise<{ id: string }> }) {
  return handle(async () => {
    const id = uuidParam.safeParse((await params).id);
    if (!id.success) return apiError('NOT_FOUND', 'Not found', 404);
    const url = new URL(request.url);
    const wanted = parseMediaVariantQuery(url.searchParams);
    if (wanted === 'invalid') return apiError('INVALID_QUERY', 'Invalid width or format', 400);
    const core = getCore();
    const asset = await getMediaAsset(core, id.data);
    if (!asset) return apiError('NOT_FOUND', 'Not found', 404);

    const isPublic = isPublicMediaKind(asset.kind);
    if (!isPublic && !(await adminForApi())) return apiError('NOT_FOUND', 'Not found', 404);

    let variant: MediaVariantRow | null = null;
    if (wanted && isPublic) {
      variant = await findMediaVariant(core.db, asset.id, wanted.format, wanted.width);
    }
    const contentHash = asset.masterSha256 ?? asset.sha256;
    const etag = variant
      ? `"${contentHash}-${variant.format}-${variant.width}"`
      : `"${contentHash}"`;
    const headers: Record<string, string> = {
      etag,
      'cache-control': !isPublic
        ? 'private, max-age=300, must-revalidate'
        : publicMediaCacheControl({
            variantRequested: wanted !== null,
            variant,
            requestedWidth: wanted?.width ?? null,
            variantsProcessed: asset.variantsProcessedAt !== null,
          }),
      'x-content-type-options': 'nosniff',
      'content-security-policy': "default-src 'none'; sandbox",
      'cross-origin-resource-policy': 'same-origin',
    };
    if (
      request.headers
        .get('if-none-match')
        ?.split(',')
        .some((v) => v.trim() === etag)
    ) {
      return new Response(null, { status: 304, headers });
    }
    const disposition = url.searchParams.get('download') === '1' ? 'attachment' : 'inline';
    const fileName = asset.fileName.replace(/[^\w.-]/g, '_');
    if (variant) {
      const bytes = await loadMediaVariantBytes(core, variant);
      return new Response(Buffer.from(bytes), {
        headers: {
          ...headers,
          'content-type': MEDIA_VARIANT_MIME[variant.format],
          'content-length': String(bytes.byteLength),
          'content-disposition': `${disposition}; filename="${fileName.replace(/\.[^.]*$/, '')}.${variant.format}"`,
        },
      });
    }
    const media = await loadMediaBytes(core, asset.id);
    return new Response(Buffer.from(media.bytes), {
      headers: {
        ...headers,
        'content-type': media.mimeType,
        'content-length': String(media.bytes.byteLength),
        'content-disposition': `${disposition}; filename="${fileName}"`,
      },
    });
  });
}
