// Locate the Android SDK when neither ANDROID_HOME/ANDROID_SDK_ROOT nor sdk.dir in local.properties
// is set (typical for command-line builds on a machine that only has Android Studio installed):
// look in the platform default install locations and write the git-ignored local.properties.
run {
    val localProps = file("local.properties")
    val props = java.util.Properties()
    if (localProps.isFile) localProps.inputStream().use { props.load(it) }
    val envSdk = listOf("ANDROID_HOME", "ANDROID_SDK_ROOT")
        .mapNotNull { System.getenv(it)?.takeIf { p -> p.isNotBlank() && File(p).isDirectory } }
        .firstOrNull()
    val configuredSdk = props.getProperty("sdk.dir")?.takeIf { File(it).isDirectory }
    if (envSdk == null && configuredSdk == null) {
        val home = System.getProperty("user.home")
        val candidates = listOfNotNull(
            System.getenv("LOCALAPPDATA")?.let { "$it\\Android\\Sdk" }, // Windows
            "$home/Library/Android/sdk", // macOS
            "$home/Android/Sdk", // Linux
        )
        val found = candidates.map(::File).firstOrNull { File(it, "platforms").isDirectory }
            ?: throw GradleException(
                "Android SDK not found. Install Android Studio (SDK Manager → Android SDK) or set " +
                    "ANDROID_HOME, or put sdk.dir=<path> into apps/android/local.properties. " +
                    "Looked in: ${candidates.joinToString()}",
            )
        props.setProperty("sdk.dir", found.absolutePath)
        localProps.outputStream().use { props.store(it, "Generated by settings.gradle.kts (Android SDK auto-detection) - machine specific, not committed") }
        logger.lifecycle("Android SDK detected at ${found.absolutePath} (written to local.properties)")
    }
}

